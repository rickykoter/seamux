#!/usr/bin/env python3
"""The board's own cat poses: the ones the Swift sidebar's cat does not have.

    python3 cat_poses.py               write them into board.html
    python3 cat_poses.py --check       exit non-zero if board.html is out of date
    python3 cat_poses.py --sheet PATH  a contact sheet of every pose, old and new

The six poses the sidebar has (nap, walk, swat) are cat_from_swift.py's and are
read out of crew.swift. These are drawn here, by hand, as ASCII grids in the
same 3px cells and the same palette, so they read as the same animal:

    hop-a, hop-b   a row turned done: crouch, then airborne, happy eyes
    heart          rises over the hop
    perk           a new row needs you: ears up
    stretch        the last thing needing you is gone: a long stretch, then nap
    peek, flick    the napping cat opens one eye, or flicks its tail

They are board-only on purpose. Nothing checks them against crew.swift, and a
change to the sidebar's cat does not reach them: cat_from_swift.py keeps this
block when it rewrites its own, and leaves it out of its --check.

Each grid row is one row of cells, a digit per cell in catColor()'s palette and
"." for empty. Rows are padded, so a grid can be ragged on the right.
"""

