BEGIN = "<!-- POSES:BEGIN generated by cat_poses.py -->"
END = "<!-- POSES:END -->"


def cells(grid):
    out = []
    for y, line in enumerate(grid.strip("\n").split("\n")):
        for x, ch in enumerate(line):
            if ch.isdigit():
                c = int(ch)
                if c not in COLOR:
                    raise SystemExit("cat_poses: colour %d is not in the palette" % c)
                out.append((x, y, c))
    return out


def paths(pixels, indent):
    lines = []
    for idx in sorted(COLOR):
        d = "".join("M%d %dh%dv%dh-%dz" % (x * PX, y * PX, PX, PX, PX)
                    for x, y, c in pixels if c == idx)
        if d:
            lines.append('%s<path fill="%s" d="%s"/>' % (indent, COLOR[idx], d))
    return lines


def block(indent="        "):
    lines = [indent + BEGIN]
    for name, grid in POSES.items():
        lines.append('%s<g class="pose x %s">' % (indent, name))
        lines += paths(cells(grid), indent + "  ")
        lines.append(indent + "</g>")
    lines.append(indent + END)
    return "\n".join(lines)


def sheet(path):
    """Every pose at 4x, the sidebar's six first, on the shelf's colour."""
    sys.path.insert(0, str(HERE))
    import cat_from_swift
    old = {n.lower().replace("_", "-"): p for n, p in cat_from_swift.poses().items()}
    allp = list(old.items()) + [(n, cells(g)) for n, g in POSES.items()]
    tiles = []
    for name, px in allp:
        body = "".join('<rect x="%d" y="%d" width="1" height="1" fill="%s"/>' % (x, y, COLOR[c])
                       for x, y, c in px)
        tiles.append('<figure><svg viewBox="-1 -1 25 14" width="125" height="70" '
                     'shape-rendering="crispEdges">%s</svg><figcaption>%s%s</figcaption></figure>'
                     % (body, name, "" if name in old else " · new"))
    html = ("<!doctype html><meta charset=utf-8><title>cat poses</title><style>"
            "body{margin:0;padding:10px;background:#2d353b;color:#d3c6aa;font:13px system-ui}"
            "main{display:grid;grid-template-columns:repeat(auto-fill,minmax(120px,1fr));gap:8px}figure{margin:0;background:#1e2326;"
            "border-radius:8px;padding:6px;text-align:center}figcaption{text-align:center;margin-top:4px}"
            "</style><main>" + "".join(tiles) + "</main>")
    pathlib.Path(path).write_text(html)
    return path


def main(argv):
    if "--sheet" in argv:
        print(sheet(argv[argv.index("--sheet") + 1]))
        return 0
    page = PAGE.read_text()
    m = re.search(r"([ \t]*)" + re.escape(BEGIN) + r".*?" + re.escape(END), page, re.S)
    if not m:
        raise SystemExit("cat_poses: the POSES markers are not in board.html "
                         "(cat_from_swift.py emits them)")
    want = block(m.group(1))
    if "--check" in argv:
        ok = re.sub(r"\s+", "", m.group(0)) == re.sub(r"\s+", "", want)
        print("board-only poses are in sync" if ok else "poses are STALE: re-run cat_poses.py")
        return 0 if ok else 1
    PAGE.write_text(page[:m.start()] + want + page[m.end():])
    print("wrote %d poses" % len(POSES))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
