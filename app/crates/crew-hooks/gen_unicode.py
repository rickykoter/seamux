#!/usr/bin/env python3
"""Regenerate src/unicode.rs from this Python's unicodedata:

    python3 app/crates/crew-hooks/gen_unicode.py > app/crates/crew-hooks/src/unicode.rs

Run it with the python3 crew's scripts run under, so the Rust reads digits
and printable characters as that Python does."""
import sys
import unicodedata

zeros = [c for c in range(0x110000) if unicodedata.category(chr(c)) == "Nd" and unicodedata.decimal(chr(c)) == 0]
runs, start = [], None
for c in range(0x110000):
    np_ = not chr(c).isprintable()
    if np_ and start is None:
        start = c
    if not np_ and start is not None:
        runs.append((start, c - 1))
        start = None
if start is not None:
    runs.append((start, 0x10ffff))
print("//! Unicode facts Python's str methods use, generated by gen_unicode.py")
print("//! from Python %s (unicodedata %s). Regenerate rather than edit.\n"
      % (sys.version.split()[0], unicodedata.unidata_version))
print("/// The code point of every Nd digit zero; each block is ten digits 0..9.")
print("pub const DIGIT_ZEROS: &[u32] = &[%s];\n" % ", ".join("0x%x" % z for z in zeros))
print("/// Inclusive runs of code points `str.isprintable()` is false for.")
print("pub const NON_PRINTABLE: &[(u32, u32)] = &[")
for i in range(0, len(runs), 6):
    print("    " + " ".join("(0x%x, 0x%x)," % r for r in runs[i:i + 6]))
print("];\n")
print('''/// `unicodedata.decimal(c)`, for float() and int().
pub fn decimal(c: char) -> Option<u32> {
    let n = c as u32;
    let i = DIGIT_ZEROS.partition_point(|&z| z <= n);
    (i > 0 && n - DIGIT_ZEROS[i - 1] < 10).then(|| n - DIGIT_ZEROS[i - 1])
}

/// `c.isprintable()`.
pub fn printable(c: char) -> bool {
    let n = c as u32;
    let i = NON_PRINTABLE.partition_point(|&(a, _)| a <= n);
    !(i > 0 && n <= NON_PRINTABLE[i - 1].1)
}''')
