const BEGIN: &str = "<!-- POSES:BEGIN generated by seamux cat_poses -->";
const END: &str = "<!-- POSES:END -->";
const CAT_BEGIN: &str = "<!-- CAT:BEGIN generated from crew.swift by seamux cat_poses -->";
const CAT_END: &str = "<!-- CAT:END -->";
/// crew.swift's poses, in the order the CAT block draws them.
const SWIFT_POSES: [&str; 6] = ["NAP_A", "NAP_B", "WALK_A", "WALK_B", "SWAT_A", "SWAT_B"];

type Px = (usize, usize, u32);

fn hex(c: u32) -> Option<&'static str> {
    COLOR.iter().find(|(i, _)| *i == c).map(|(_, h)| *h)
}

/// A grid's pixels, row by row; a digit outside the palette is an error.
fn cells(grid: &str) -> Result<Vec<Px>, String> {
    let mut out = Vec::new();
    for (y, line) in grid.trim_matches('\n').split('\n').enumerate() {
        for (x, ch) in line.chars().enumerate() {
            if let Some(c) = ch.to_digit(10) {
                if hex(c).is_none() {
                    return Err(format!("cat_poses: colour {c} is not in the palette"));
                }
                out.push((x, y, c));
            }
        }
    }
    Ok(out)
}

fn paths(pixels: &[Px], indent: &str) -> Vec<String> {
    let mut lines = Vec::new();
    for (idx, h) in COLOR {
        let d: String = pixels
            .iter()
            .filter(|p| p.2 == idx)
            .map(|(x, y, _)| format!("M{} {}h{}v{}h-{}z", x * PX, y * PX, PX, PX, PX))
            .collect();
        if !d.is_empty() {
            lines.push(format!("{indent}<path fill=\"{h}\" d=\"{d}\"/>"));
        }
    }
    lines
}

/// The POSES block, at `indent`.
pub fn block(indent: &str) -> Result<String, String> {
    let mut lines = vec![format!("{indent}{BEGIN}")];
    for (name, grid) in POSES {
        lines.push(format!("{indent}<g class=\"pose x {name}\">"));
        lines.extend(paths(&cells(grid)?, &format!("{indent}  ")));
        lines.push(format!("{indent}</g>"));
    }
    lines.push(format!("{indent}{END}"));
    Ok(lines.join("\n"))
}

/// The span `([ \t]*)BEGIN.*?END` matches, and its indent: (start, end, indent).
fn find_block(page: &str) -> Option<(usize, usize, String)> {
    let b = page.find(BEGIN)?;
    let e = b + page[b..].find(END)? + END.len();
    let start = page[..b].trim_end_matches([' ', '\t']).len();
    Some((start, e, page[start..b].to_string()))
}

fn squash(s: &str) -> String {
    s.chars().filter(|c| !c.is_whitespace()).collect()
}

fn page_path() -> PathBuf {
    crew_core::crew_home().join("board").join("board.html")
}

/// The sidebar's poses, as --from-swift drew them into board.html:
/// (name, pixels in cells).
fn sidebar_poses(page: &str) -> Vec<(String, Vec<Px>)> {
    let Some(b) = page.find(CAT_BEGIN) else { return Vec::new() };
    let Some(e) = page[b..].find(CAT_END) else { return Vec::new() };
    let mut cat = page[b..b + e].to_string();
    if let Some((s, t, _)) = find_block(&cat) {
        cat.replace_range(s..t, "");
    }
    let mut out: Vec<(String, Vec<Px>)> = Vec::new();
    let open = "<g class=\"pose ";
    let mut rest = cat.as_str();
    while let Some(i) = rest.find(open) {
        rest = &rest[i + open.len()..];
        let Some(q) = rest.find('"') else { break };
        let name = rest[..q].to_string();
        let body_end = rest.find("</g>").unwrap_or(rest.len());
        let body = &rest[..body_end];
        let mut px = Vec::new();
        for path in body.split("<path ").skip(1) {
            let fill = path.split("fill=\"").nth(1).and_then(|s| s.split('"').next()).unwrap_or("");
            let Some(c) = COLOR.iter().find(|(_, h)| *h == fill).map(|(i, _)| *i) else { continue };
            let d = path.split("d=\"").nth(1).and_then(|s| s.split('"').next()).unwrap_or("");
            for cmd in d.split('M').skip(1) {
                let xy: String = cmd.chars().take_while(|ch| *ch != 'h').collect();
                let mut it = xy.split_whitespace().filter_map(|n| n.parse::<usize>().ok());
                if let (Some(x), Some(y)) = (it.next(), it.next()) {
                    px.push((x / PX, y / PX, c));
                }
            }
        }
        out.push((name, px));
        rest = &rest[body_end..];
    }
    out
}

/// Every pose at 4x, the sidebar's six first, on the shelf's colour.
fn sheet(path: &Path, page: &str) -> Result<(), String> {
    let old = sidebar_poses(page);
    let mut all: Vec<(String, Vec<Px>, bool)> = old.into_iter().map(|(n, p)| (n, p, false)).collect();
    for (name, grid) in POSES {
        all.push((name.to_string(), cells(grid)?, true));
    }
    let tiles: String = all
        .iter()
        .map(|(name, px, new)| {
            let body: String = px
                .iter()
                .map(|(x, y, c)| format!("<rect x=\"{x}\" y=\"{y}\" width=\"1\" height=\"1\" fill=\"{}\"/>", hex(*c).unwrap_or("")))
                .collect();
            format!(
                "<figure><svg viewBox=\"-1 -1 25 14\" width=\"125\" height=\"70\" shape-rendering=\"crispEdges\">{body}</svg><figcaption>{name}{}</figcaption></figure>",
                if *new { " · new" } else { "" }
            )
        })
        .collect();
    let html = format!(
        "<!doctype html><meta charset=utf-8><title>cat poses</title><style>\
body{{margin:0;padding:10px;background:#2d353b;color:#d3c6aa;font:13px system-ui}}\
main{{display:grid;grid-template-columns:repeat(auto-fill,minmax(120px,1fr));gap:8px}}figure{{margin:0;background:#1e2326;\
border-radius:8px;padding:6px;text-align:center}}figcaption{{text-align:center;margin-top:4px}}\
</style><main>{tiles}</main>"
    );
    std::fs::write(path, html).map_err(|e| crew_core::py::os_error(&e, path))
}

/// The installed sidebar when there is one, else the crew tree's own copy:
/// the same file either way (install.sh copies it verbatim).
fn swift_path() -> PathBuf {
    let installed = crew_core::py::home().join(".config/cmux/sidebars/crew.swift");
    if installed.exists() {
        installed
    } else {
        crew_core::crew_home().join("sidebars").join("crew.swift")
    }
}

/// Each pose's `let NAME = [[x, y, c], ...]` in crew.swift, as pixels.
fn swift_poses(src: &str) -> Result<Vec<(&'static str, Vec<Px>)>, String> {
    let triple = regex::Regex::new(r"\[\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\]").expect("static regex");
    let mut out = Vec::new();
    for name in SWIFT_POSES {
        let head = format!("let {name} = [[");
        let start = src.find(&head).ok_or(format!("cat_poses: {name} not found in crew.swift"))? + head.len() - 2;
        let end = start + src[start..].find("]]\n").ok_or(format!("cat_poses: {name} has no end"))? + 2;
        let px = triple
            .captures_iter(&src[start..end])
            .map(|c| (c[1].parse().unwrap_or(0), c[2].parse().unwrap_or(0), c[3].parse().unwrap_or(0)))
            .collect();
        out.push((name, px));
    }
    Ok(out)
}

/// The CAT block: crew.swift's six poses, an empty POSES block inside them.
fn sprite(poses: &[(&str, Vec<Px>)]) -> String {
    let all = || poses.iter().flat_map(|(_, p)| p.iter());
    // Widest pose plus the pace travel, so the cat never clips as it walks.
    let span = all().map(|p| p.0).max().unwrap_or(0) + 1;
    let (w, h) = (span * PX + 36, (all().map(|p| p.1).max().unwrap_or(0) + 2) * PX);
    let mut lines = vec![
        CAT_BEGIN.to_string(),
        format!("    <svg id=\"cat\" class=\"nap\" viewBox=\"0 0 {w} {h}\" aria-hidden=\"true\">"),
        "      <g class=\"walker\"><g class=\"facing\">".to_string(),
    ];
    for (name, px) in poses {
        lines.push(format!("        <g class=\"pose {}\">", name.to_lowercase().replace('_', "-")));
        lines.extend(paths(px, "          "));
        lines.push("        </g>".to_string());
    }
    lines.push(format!("        {BEGIN}"));
    lines.push(format!("        {END}"));
    lines.push("      </g></g>".to_string());
    // Three z's on staggered phases: a breathing curve alone reads as a
    // static sprite at this size, and drifting z's are unmistakable.
    for i in 0..3 {
        lines.push(format!("      <text class=\"zz z{i}\" x=\"{}\" y=\"{}\">z</text>", 44 + i * 5, 14 - i * 2));
    }
    lines.push("    </svg>".to_string());
    lines.push(format!("    {CAT_END}"));
    lines.join("\n")
}

/// The POSES span without its indent: (start, end).
fn poses_span(s: &str) -> Option<(usize, usize)> {
    let b = s.find(BEGIN)?;
    Some((b, b + s[b..].find(END)? + END.len()))
}

fn from_swift(page_file: &Path, check: bool) -> Result<i32, String> {
    let swift = swift_path();
    let src = std::fs::read_to_string(&swift).map_err(|e| crew_core::py::os_error(&e, &swift))?;
    let poses = swift_poses(&src)?;
    let mut want = sprite(&poses);
    let page = std::fs::read_to_string(page_file).map_err(|e| crew_core::py::os_error(&e, page_file))?;
    let (Some(i), Some(j)) = (page.find(CAT_BEGIN), page.find(CAT_END)) else {
        return Err("cat_poses: the CAT markers are not in board.html".into());
    };
    let have = page[i..j + CAT_END.len()].trim_end().to_string();
    if check {
        // The sprite only: whitespace aside, and the board's own poses out.
        let bare = |s: &str| {
            let mut s = s.to_string();
            if let Some((a, b)) = poses_span(&s) {
                s.replace_range(a..b, "");
            }
            squash(&s)
        };
        let ok = bare(&have) == bare(&want);
        println!("{}", if ok { "cat is in sync with crew.swift" } else { "cat is STALE: re-run seamux cat_poses --from-swift" });
        return Ok(if ok { 0 } else { 1 });
    }
    if let (Some((a, b)), Some((c, d))) = (poses_span(&want), poses_span(&have)) {
        want.replace_range(a..b, &have[c..d]);
    }
    let out = format!("{}{}{}", &page[..i], want, &page[j + CAT_END.len()..]);
    std::fs::write(page_file, out).map_err(|e| crew_core::py::os_error(&e, page_file))?;
    let n: usize = poses.iter().map(|(_, p)| p.len()).sum();
    println!("wrote {} poses, {n} pixels", poses.len());
    Ok(0)
}

fn run(args: &[String]) -> Result<i32, String> {
    let page_file = page_path();
    if args.iter().any(|a| a == "--from-swift") {
        return from_swift(&page_file, args.iter().any(|a| a == "--check"));
    }
    let read = || std::fs::read_to_string(&page_file).map_err(|e| crew_core::py::os_error(&e, &page_file));
    if let Some(i) = args.iter().position(|a| a == "--sheet") {
        let out = args.get(i + 1).ok_or("cat_poses: --sheet needs a path")?;
        sheet(Path::new(out), &read().unwrap_or_default())?;
        println!("{out}");
        return Ok(0);
    }
    let page = read()?;
    let (start, end, indent) = find_block(&page).ok_or(
        "cat_poses: the POSES markers are not in board.html (--from-swift emits them)",
    )?;
    let want = block(&indent)?;
    if args.iter().any(|a| a == "--check") {
        let ok = squash(&page[start..end]) == squash(&want);
        println!("{}", if ok { "board-only poses are in sync" } else { "poses are STALE: re-run seamux cat_poses" });
        return Ok(if ok { 0 } else { 1 });
    }
    let mut out = String::with_capacity(page.len());
    out.push_str(&page[..start]);
    out.push_str(&want);
    out.push_str(&page[end..]);
    std::fs::write(&page_file, out).map_err(|e| crew_core::py::os_error(&e, &page_file))?;
    println!("wrote {} poses", POSES.len());
    Ok(0)
}

pub fn main(args: &[String]) -> i32 {
    match run(args) {
        Ok(code) => code,
        Err(e) => {
            eprintln!("{e}");
            1
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn block_round_trips_through_check() {
        let page = format!("<svg>\n  {}\n  stale\n  {}\n</svg>", BEGIN, END);
        let (s, e, indent) = find_block(&page).unwrap();
        assert_eq!(indent, "  ");
        let fresh = format!("{}{}{}", &page[..s], block(&indent).unwrap(), &page[e..]);
        let (s2, e2, _) = find_block(&fresh).unwrap();
        assert_eq!(squash(&fresh[s2..e2]), squash(&block("").unwrap()));
    }

    #[test]
    fn swift_poses_are_read_and_drawn_with_the_poses_block_inside() {
        let src: String = SWIFT_POSES
            .iter()
            .enumerate()
            .map(|(i, n)| format!("    let {n} = [[{i}, 1, 1], [2, 3,\n 4]]\n"))
            .collect();
        let poses = swift_poses(&src).unwrap();
        assert_eq!(poses[0].1, vec![(0, 1, 1), (2, 3, 4)]);
        assert_eq!(poses[5].1[0], (5, 1, 1));
        let svg = sprite(&poses);
        // Widest x is 5: (5 + 1) * 3 + 36 wide; deepest y is 3: (3 + 2) * 3 high.
        assert!(svg.contains("viewBox=\"0 0 54 15\""), "{svg}");
        assert!(svg.starts_with(CAT_BEGIN) && svg.ends_with(CAT_END));
        assert!(svg.contains("<g class=\"pose swat-b\">"));
        let (a, b) = poses_span(&svg).unwrap();
        assert!(svg[a..b].starts_with(BEGIN) && svg[a..b].ends_with(END));
        assert!(swift_poses("let NAP_A = [[1, 1, 1]]\n").unwrap_err().contains("NAP_B"));
    }

    #[test]
    fn a_heart_is_pink() {
        let px = cells(POSES[2].1).unwrap();
        assert!(px.iter().all(|p| p.2 == 4));
        assert_eq!(paths(&px, "").len(), 1);
    }
}
