//! The board's cat sprite, in board.html.
//!
//!   seamux cat_poses                     write the board's own poses
//!   seamux cat_poses --check             exit 1 if they are out of date
//!   seamux cat_poses --from-swift        redraw the sprite from crew.swift
//!   seamux cat_poses --from-swift --check  exit 1 if the sprite is stale
//!   seamux cat_poses --sheet PATH        a contact sheet of every pose
//!
//! The sprite's six poses are the Swift sidebar's cat, read straight out of
//! crew.swift's [[x, y, colour], ...] arrays (--from-swift), so the board and
//! the sidebar show the same animal, pixel for pixel. Each pose is one
//! <path> per colour, every pixel a 3x3 square, in a CAT block. The board's
//! own poses (a hop, a stretch...), drawn by hand below as grids of 3px cells
//! in the same palette, live in a POSES block inside it, so they walk, turn
//! and bob with the rest of the cat. --from-swift keeps that block, and its
//! --check leaves it out: those poses are not crew.swift's to vouch for.

use std::path::{Path, PathBuf};

const PX: usize = 3;

