//! The board's own cat poses, the ones the Swift sidebar's cat does not have
//! (crew/board/cat_poses.py).
//!
//!   seamux cat_poses               write them into board.html
//!   seamux cat_poses --check       exit 1 if board.html is out of date
//!   seamux cat_poses --sheet PATH  a contact sheet of every pose, old and new
//!
//! Drawn by hand as grids of 3px cells in the sidebar cat's palette. The
//! sidebar's six poses are cat_from_swift.py's, which reads crew.swift; that
//! script is not ported (the cutover deletes crew.swift), so the sheet reads
//! those six back out of the CAT block cat_from_swift.py wrote into
//! board.html. Same pixels as the Python's sheet, listed colour by colour.

