//! The shelf's sprites: the board's sheets and the app's copy, from one source.
//!
//!   seamux sprites               write both copies from crew/board/sprites/*.json
//!   seamux sprites --check       exit 1 if either copy is out of date
//!   seamux sprites --sheet PATH  a contact sheet of every frame of every sprite
//!
//! Each sprite is a JSON file: a palette of one-character keys and 18 frames of
//! 24x15 cells ('.' is empty), in the frame order below. Two copies are made:
//!
//! - board.html's SPRITES block: one SVG sheet per sprite (its 18 frames side
//!   by side, 2px a cell) as a data: image, picked by #cat's data-sprite, and
//!   the keyframes that step through it. The page stays script-free: CSS moves
//!   background-position, and render.js only sets the mood class.
//! - app/ui/sprites.gen.ts beside the crew tree, when it is a checkout: the
//!   grids themselves, for the pane peek, search and the Tray.
//!
//! Neither copy is edited by hand (ADR: sprites have one source).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// Cells a frame is wide and tall, and CSS pixels a cell.
pub const W: usize = 24;
pub const H: usize = 15;
const PX: usize = 2;

/// Every sprite's frames, in sheet order: frame k sits at x = -k * W * PX.
pub const FRAMES: [&str; 18] = [
    "sit", "sit-blink", "perk", "nap-a", "nap-b", "nap-peek", "nap-flick", "walk-1", "walk-2", "walk-3", "walk-4",
    "swat-a", "swat-b", "hop-crouch", "hop-air", "stretch-a", "stretch-b", "heart",
];

/// The sprite shown when none is chosen.
pub const DEFAULT: &str = "tuxedo";

const BEGIN: &str = "<!-- SPRITES:BEGIN generated by seamux sprites -->";
const END: &str = "<!-- SPRITES:END -->";

#[derive(Debug, Clone)]
pub struct Sprite {
    pub id: String,
    pub name: String,
    pub order: i64,
    pub palette: BTreeMap<char, String>,
    /// In FRAMES order, each H rows of W chars.
    pub frames: Vec<Vec<String>>,
}

fn frame_index(name: &str) -> usize {
    FRAMES.iter().position(|f| *f == name).expect("a frame in FRAMES")
}

/// One sprite from its JSON, checked: the id matches the file, every frame is
/// there and W x H, and every cell is '.' or a palette key.
pub fn parse(stem: &str, src: &str) -> Result<Sprite, String> {
    let at = |m: String| format!("sprites: {stem}.json: {m}");
    let v: serde_json::Value = serde_json::from_str(src).map_err(|e| at(e.to_string()))?;
    let id = v["id"].as_str().ok_or_else(|| at("no id".into()))?.to_string();
    if id != stem {
        return Err(at(format!("id {id:?} is not the file's name")));
    }
    if !id.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-') {
        return Err(at(format!("id {id:?}: lowercase letters, digits and - only")));
    }
    let name = v["name"].as_str().ok_or_else(|| at("no name".into()))?.to_string();
    let order = v["order"].as_i64().ok_or_else(|| at("no order".into()))?;
    let mut palette = BTreeMap::new();
    for (k, c) in v["palette"].as_object().ok_or_else(|| at("no palette".into()))? {
        let mut ch = k.chars();
        let (Some(key), None) = (ch.next(), ch.next()) else { return Err(at(format!("palette key {k:?} is not one character"))) };
        let c = c.as_str().unwrap_or("");
        let hex = c.len() == 7 && c.starts_with('#') && c[1..].chars().all(|d| d.is_ascii_hexdigit());
        if key == '.' || !hex {
            return Err(at(format!("palette {k:?}: {c:?} is not #rrggbb")));
        }
        palette.insert(key, c.to_string());
    }
    let obj = v["frames"].as_object().ok_or_else(|| at("no frames".into()))?;
    if let Some(extra) = obj.keys().find(|k| !FRAMES.contains(&k.as_str())) {
        return Err(at(format!("unknown frame {extra:?}")));
    }
    let mut frames = Vec::new();
    for f in FRAMES {
        let rows = obj.get(f).and_then(|r| r.as_array()).ok_or_else(|| at(format!("missing frame {f}")))?;
        if rows.len() != H {
            return Err(at(format!("{f}: {} rows, want {H}", rows.len())));
        }
        let mut out = Vec::new();
        for (y, r) in rows.iter().enumerate() {
            let r = r.as_str().unwrap_or("");
            if r.chars().count() != W {
                return Err(at(format!("{f} row {y}: {} cells, want {W}", r.chars().count())));
            }
            if let Some(c) = r.chars().find(|c| *c != '.' && !palette.contains_key(c)) {
                return Err(at(format!("{f} row {y}: {c:?} is not in the palette")));
            }
            out.push(r.to_string());
        }
        frames.push(out);
    }
    Ok(Sprite { id, name, order, palette, frames })
}

/// Every sprite in `dir`, by order then id; the default must be among them.
pub fn load(dir: &Path) -> Result<Vec<Sprite>, String> {
    let rd = std::fs::read_dir(dir).map_err(|e| crew_core::py::os_error(&e, dir))?;
    let mut out = Vec::new();
    for e in rd.flatten() {
        let p = e.path();
        if p.extension().and_then(|x| x.to_str()) != Some("json") {
            continue;
        }
        let stem = p.file_stem().and_then(|s| s.to_str()).unwrap_or("").to_string();
        let src = std::fs::read_to_string(&p).map_err(|e| crew_core::py::os_error(&e, &p))?;
        out.push(parse(&stem, &src)?);
    }
    out.sort_by(|a, b| a.order.cmp(&b.order).then(a.id.cmp(&b.id)));
    if !out.iter().any(|s| s.id == DEFAULT) {
        return Err(format!("sprites: no {DEFAULT}.json in {}", dir.display()));
    }
    Ok(out)
}

/// A sprite's sheet as SVG: one path per colour, each run of same-coloured
/// cells in a row one rectangle, every frame W cells to the right of the last.
pub fn sheet_svg(s: &Sprite) -> String {
    let mut by_colour: BTreeMap<&char, String> = BTreeMap::new();
    for (k, rows) in s.frames.iter().enumerate() {
        for (y, row) in rows.iter().enumerate() {
            let cells: Vec<char> = row.chars().collect();
            let mut x = 0;
            while x < W {
                let c = cells[x];
                let mut n = 1;
                while x + n < W && cells[x + n] == c {
                    n += 1;
                }
                if c != '.' {
                    let d = by_colour.entry(s.palette.get_key_value(&c).map(|kv| kv.0).expect("checked")).or_default();
                    d.push_str(&format!("M{} {}h{}v1h-{}z", k * W + x, y, n, n));
                }
                x += n;
            }
        }
    }
    let paths: String = by_colour.iter().map(|(c, d)| format!("<path fill='{}' d='{d}'/>", s.palette[*c])).collect();
    format!(
        "<svg xmlns='http://www.w3.org/2000/svg' width='{}' height='{}' viewBox='0 0 {} {H}' shape-rendering='crispEdges'>{paths}</svg>",
        W * PX * FRAMES.len(),
        H * PX,
        W * FRAMES.len()
    )
}

/// The SVG as a CSS url("data:...") value.
fn data_url(svg: &str) -> String {
    let mut out = String::from("url(\"data:image/svg+xml,");
    for ch in svg.chars() {
        match ch {
            '%' => out.push_str("%25"),
            '#' => out.push_str("%23"),
            '<' => out.push_str("%3C"),
            '>' => out.push_str("%3E"),
            '"' => out.push_str("%22"),
            c => out.push(c),
        }
    }
    out.push_str("\")");
    out
}

/// A move: its length in seconds, and the frame from each start time on.
pub struct Timeline {
    pub name: &'static str,
    pub secs: f64,
    pub steps: Vec<(f64, &'static str)>,
}

/// The board's moves. Pace walks in bursts: about 6s of the walk at 8 fps,
/// then 4s sitting and looking about (ADR: the walk is in bursts).
pub fn timelines() -> Vec<Timeline> {
    // Nap: breathe on a 6s cycle; one eye open now and then, a tail flick once,
    // unevenly spaced over one 48s cycle so it reads as a cat, not a metronome.
    let mut nap: Vec<(f64, &str)> = (0..16).map(|k| (3.0 * k as f64, if k % 2 == 0 { "nap-a" } else { "nap-b" })).collect();
    for (from, to, f) in [(10.0, 11.4, "nap-peek"), (24.0, 24.7, "nap-flick"), (37.0, 38.0, "nap-peek")] {
        let back = nap.iter().rev().find(|(t, _)| *t <= to).map(|s| s.1).unwrap_or("nap-a");
        nap.retain(|(t, _)| *t < from || *t > to);
        nap.push((from, f));
        nap.push((to, back));
    }
    nap.sort_by(|a, b| a.0.total_cmp(&b.0));
    let walk = ["walk-1", "walk-2", "walk-3", "walk-4"];
    let mut legs: Vec<(f64, &str)> = (0..48).map(|k| (k as f64 * 0.125, walk[k % 4])).collect();
    legs.extend([(6.0, "sit"), (8.0, "sit-blink"), (8.2, "sit"), (9.0, "perk"), (9.8, "sit")]);
    let mut swat: Vec<(f64, &str)> = (0..22).map(|k| (k as f64 * 0.25, if k % 2 == 0 { "swat-a" } else { "swat-b" })).collect();
    swat.extend([(5.5, "sit-blink"), (5.75, "swat-a")]);
    vec![
        Timeline { name: "nap", secs: 48.0, steps: nap },
        Timeline { name: "pace", secs: 10.0, steps: legs },
        Timeline { name: "swat", secs: 6.0, steps: swat },
        Timeline { name: "hop", secs: 1.6, steps: vec![(0.0, "hop-crouch"), (0.3, "hop-air"), (0.9, "hop-crouch"), (1.15, "sit")] },
        Timeline { name: "perk", secs: 1.2, steps: vec![(0.0, "perk")] },
        Timeline { name: "stretch", secs: 2.4, steps: vec![(0.0, "stretch-a"), (0.45, "stretch-b"), (2.0, "stretch-a")] },
    ]
}

fn pct(t: f64, secs: f64) -> String {
    let p = (t / secs * 100.0 * 1000.0).round() / 1000.0;
    format!("{p}%")
}

fn pos(frame: &str) -> String {
    let k = frame_index(frame);
    if k == 0 { "0 0".into() } else { format!("-{}px 0", k * W * PX) }
}

/// The frame keyframes, one @keyframes sp-<move> per timeline, each step held
/// (the rules that use them say steps(1,end)), the last frame held to 100%.
fn frame_keyframes(t: &Timeline) -> String {
    let mut body = String::new();
    for (at, f) in &t.steps {
        body.push_str(&format!("{}{{background-position:{}}}", pct(*at, t.secs), pos(f)));
    }
    let last = t.steps.last().map(|s| s.1).unwrap_or("sit");
    body.push_str(&format!("100%{{background-position:{}}}", pos(last)));
    format!("@keyframes sp-{}{{{body}}}", t.name)
}

/// The walk along the shelf over six bursts (three out, three back): 60s, in
/// step with pace's 10s. Moving in 48 steps a burst, held while it sits.
fn travel_keyframes() -> String {
    let at = |f: f64| format!("left:calc((100% - {}px) * {f:.4})", W * PX);
    let mut body = String::new();
    for b in 0..6 {
        let (from, to) = if b < 3 { (b as f64 / 3.0, (b + 1) as f64 / 3.0) } else { ((6 - b) as f64 / 3.0, (5 - b) as f64 / 3.0) };
        let t = 10.0 * b as f64;
        body.push_str(&format!("{}{{{};animation-timing-function:steps(48,end)}}", pct(t, 60.0), at(from)));
        body.push_str(&format!("{}{{{};animation-timing-function:steps(1,end)}}", pct(t + 6.0, 60.0), at(to)));
    }
    body.push_str(&format!("100%{{{}}}", at(0.0)));
    format!("@keyframes sp-travel{{{body}}}")
}

/// board.html's SPRITES block, at `indent`: a <style> with each sprite's sheet
/// and the keyframes.
pub fn board_block(sprites: &[Sprite], indent: &str) -> String {
    let mut css = Vec::new();
    for s in sprites {
        let sel = if s.id == DEFAULT {
            "#cat .body,#cat .heart".to_string()
        } else {
            format!("#cat[data-sprite={0}] .body,#cat[data-sprite={0}] .heart", s.id)
        };
        css.push(format!("{sel}{{background-image:{}}}", data_url(&sheet_svg(s))));
    }
    for t in timelines() {
        css.push(frame_keyframes(&t));
    }
    css.push(travel_keyframes());
    let mut lines = vec![format!("{indent}{BEGIN}"), format!("{indent}<style id=\"sprites\">")];
    lines.extend(css.into_iter().map(|c| format!("{indent}{c}")));
    lines.push(format!("{indent}</style>"));
    lines.push(format!("{indent}{END}"));
    lines.join("\n")
}

/// app/ui/sprites.gen.ts: the grids, for the app.
pub fn app_module(sprites: &[Sprite]) -> String {
    let q = |s: &str| serde_json::to_string(s).expect("a string");
    let mut out = String::from(
        "// Generated by `seamux sprites` from crew/board/sprites/*.json: edit those and\n\
         // run it again, never this file (`seamux sprites --check` fails when it is stale).\n\n",
    );
    out.push_str(&format!("export const FRAMES = [{}] as const;\n", FRAMES.iter().map(|f| q(f)).collect::<Vec<_>>().join(", ")));
    out.push_str("export type Frame = (typeof FRAMES)[number];\n");
    out.push_str(&format!(
        "export const SPRITE_IDS = [{}] as const;\n",
        sprites.iter().map(|s| q(&s.id)).collect::<Vec<_>>().join(", ")
    ));
    out.push_str("export type SpriteId = (typeof SPRITE_IDS)[number];\n");
    out.push_str(&format!("export const DEFAULT_SPRITE: SpriteId = {};\n", q(DEFAULT)));
    out.push_str(&format!("/** Cells a frame is wide and tall. */\nexport const W = {W};\nexport const H = {H};\n\n"));
    out.push_str("export type Sprite = { name: string; palette: Record<string, string>; frames: Record<Frame, string[]> };\n\n");
    out.push_str("export const SPRITES: Record<SpriteId, Sprite> = {\n");
    for s in sprites {
        out.push_str(&format!("  {}: {{\n    name: {},\n    palette: {{ ", q(&s.id), q(&s.name)));
        out.push_str(&s.palette.iter().map(|(k, v)| format!("{}: {}", q(&k.to_string()), q(v))).collect::<Vec<_>>().join(", "));
        out.push_str(" },\n    frames: {\n");
        for (k, rows) in s.frames.iter().enumerate() {
            out.push_str(&format!("      {}: [\n", q(FRAMES[k])));
            for r in rows {
                out.push_str(&format!("        {},\n", q(r)));
            }
            out.push_str("      ],\n");
        }
        out.push_str("    },\n  },\n");
    }
    out.push_str("};\n");
    out
}

/// The span `([ \t]*)BEGIN.*?END` matches, and its indent: (start, end, indent).
fn find_block(page: &str) -> Option<(usize, usize, String)> {
    let b = page.find(BEGIN)?;
    let e = b + page[b..].find(END)? + END.len();
    let start = page[..b].trim_end_matches([' ', '\t']).len();
    Some((start, e, page[start..b].to_string()))
}

fn sprites_dir() -> PathBuf {
    crew_core::crew_home().join("board").join("sprites")
}

fn page_path() -> PathBuf {
    crew_core::crew_home().join("board").join("board.html")
}

/// The app's copy, when the crew tree is a checkout's (it has ../app/ui).
fn app_path() -> Option<PathBuf> {
    let ui = crew_core::crew_home().join("..").join("app").join("ui");
    ui.is_dir().then(|| ui.join("sprites.gen.ts"))
}

/// Every frame of every sprite, on the dark and the light shelf.
fn contact_sheet(path: &Path, sprites: &[Sprite]) -> Result<(), String> {
    let mut rows = String::new();
    for s in sprites {
        let img = data_url(&sheet_svg(s));
        let cells: String = FRAMES
            .iter()
            .enumerate()
            .map(|(k, f)| {
                format!(
                    "<figure><i style='background-image:{img};background-position:-{}px 0'></i><figcaption>{f}</figcaption></figure>",
                    k * W * PX * 2
                )
            })
            .collect();
        rows.push_str(&format!("<h2>{}</h2><main>{cells}</main>", s.name));
    }
    let html = format!(
        "<!doctype html><meta charset=utf-8><title>sprites</title><style>\
body{{margin:0;padding:10px;background:#2d353b;color:#d3c6aa;font:13px system-ui}}h2{{font-size:14px;margin:14px 0 6px}}\
main{{display:grid;grid-template-columns:repeat(auto-fill,minmax(110px,1fr));gap:6px}}figure{{margin:0;text-align:center}}\
i{{display:block;margin:auto;width:96px;height:60px;background-size:{}px 60px;background-repeat:no-repeat;\
background-color:#1e2326;box-shadow:0 66px 0 #e6e2cc}}figcaption{{margin-top:70px}}</style>{rows}",
        W * PX * 2 * FRAMES.len()
    );
    std::fs::write(path, html).map_err(|e| crew_core::py::os_error(&e, path))
}

fn run(args: &[String]) -> Result<i32, String> {
    let sprites = load(&sprites_dir())?;
    if let Some(i) = args.iter().position(|a| a == "--sheet") {
        let out = args.get(i + 1).ok_or("sprites: --sheet needs a path")?;
        contact_sheet(Path::new(out), &sprites)?;
        println!("{out}");
        return Ok(0);
    }
    let check = args.iter().any(|a| a == "--check");
    let page_file = page_path();
    let page = std::fs::read_to_string(&page_file).map_err(|e| crew_core::py::os_error(&e, &page_file))?;
    let (start, end, indent) = find_block(&page).ok_or("sprites: the SPRITES markers are not in board.html")?;
    let want = board_block(&sprites, &indent);
    let page_ok = page[start..end] == want;
    let app = app_path();
    let app_want = app_module(&sprites);
    let app_ok = app.as_ref().is_none_or(|p| std::fs::read_to_string(p).is_ok_and(|have| have == app_want));
    if check {
        let ok = page_ok && app_ok;
        let stale: Vec<&str> = [(!page_ok).then_some("board.html"), (!app_ok).then_some("app/ui/sprites.gen.ts")].into_iter().flatten().collect();
        println!("{}", if ok { "sprites are in sync".to_string() } else { format!("sprites are STALE in {}: re-run seamux sprites", stale.join(" and ")) });
        return Ok(if ok { 0 } else { 1 });
    }
    if !page_ok {
        std::fs::write(&page_file, format!("{}{}{}", &page[..start], want, &page[end..])).map_err(|e| crew_core::py::os_error(&e, &page_file))?;
    }
    if let (Some(p), false) = (&app, app_ok) {
        std::fs::write(p, &app_want).map_err(|e| crew_core::py::os_error(&e, p))?;
    }
    println!(
        "wrote {} sprites{}",
        sprites.len(),
        if app.is_some() { " to board.html and app/ui/sprites.gen.ts" } else { " to board.html (no app/ui beside this crew tree)" }
    );
    Ok(0)
}

pub fn main(args: &[String]) -> i32 {
    match run(args) {
        Ok(code) => code,
        Err(e) => {
            eprintln!("{e}");
            1
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tiny(id: &str) -> String {
        let row = |c: char| format!("\"{}\"", c.to_string().repeat(W));
        let frame = format!("[{}]", (0..H).map(|y| row(if y == 0 { 'a' } else { '.' })).collect::<Vec<_>>().join(","));
        let frames = FRAMES.iter().map(|f| format!("\"{f}\":{frame}")).collect::<Vec<_>>().join(",");
        format!("{{\"id\":\"{id}\",\"name\":\"T\",\"order\":1,\"palette\":{{\"a\":\"#112233\"}},\"frames\":{{{frames}}}}}")
    }

    #[test]
    fn a_sprite_is_checked_cell_by_cell() {
        assert!(parse("t", &tiny("t")).is_ok());
        assert!(parse("u", &tiny("t")).unwrap_err().contains("not the file's name"));
        assert!(parse("t", &tiny("t").replacen("\"aaaaaaaaaaaaaaaaaaaaaaaa\"", "\"aaa\"", 1)).unwrap_err().contains("want 24"));
        assert!(parse("t", &tiny("t").replacen("\"aaaaaaaaaaaaaaaaaaaaaaaa\"", "\"aaaaaaaaaaaaaaaaaaaaaaab\"", 1)).unwrap_err().contains("not in the palette"));
        assert!(parse("t", &tiny("t").replace("\"heart\":", "\"hearts\":")).unwrap_err().contains("unknown frame"));
    }

    #[test]
    fn a_run_of_cells_is_one_rectangle_and_frames_sit_side_by_side() {
        let s = parse("t", &tiny("t")).unwrap();
        let svg = sheet_svg(&s);
        assert!(svg.contains("M0 0h24v1h-24z") && svg.contains("M24 0h24v1h-24z"), "{svg}");
        assert!(svg.contains(&format!("width='{}' height='30'", 48 * 18)));
        assert_eq!(svg.matches("<path").count(), 1);
    }

    #[test]
    fn the_default_sprite_is_the_unqualified_rule() {
        let s = parse("tuxedo", &tiny("tuxedo")).unwrap();
        let mut o = parse("owl", &tiny("owl")).unwrap();
        o.order = 2;
        let b = board_block(&[s, o], "  ");
        assert!(b.contains("#cat .body,#cat .heart{background-image:url(\"data:image/svg+xml,"));
        assert!(b.contains("#cat[data-sprite=owl] .body,#cat[data-sprite=owl] .heart{"));
        assert!(!b.contains("<svg") && b.contains("%23112233"), "the sheet is url-encoded");
    }

    #[test]
    fn timelines_start_at_zero_stay_in_order_and_name_real_frames() {
        for t in timelines() {
            assert_eq!(t.steps[0].0, 0.0, "{}", t.name);
            assert!(t.steps.windows(2).all(|w| w[0].0 < w[1].0), "{}", t.name);
            assert!(t.steps.iter().all(|s| s.0 < t.secs && FRAMES.contains(&s.1)), "{}", t.name);
        }
        let nap = timelines().into_iter().find(|t| t.name == "nap").unwrap();
        assert!(nap.steps.iter().any(|s| s.1 == "nap-peek") && nap.steps.iter().any(|s| s.1 == "nap-flick"));
        let pace = timelines().into_iter().find(|t| t.name == "pace").unwrap();
        assert_eq!(pace.steps.iter().filter(|s| s.1.starts_with("walk-")).count(), 48);
    }
}
